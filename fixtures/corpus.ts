import type { TaggedSentence } from '../src/core/types.js';

/**
 * 合成中文词性标注语料夹具。
 * 标签集：N名词 V动词 A形容词 ADV副词 P介词 NUM数词 M量词
 *          PRON代词 CONJ连词 PUNCT标点 X罕见/其他
 * 覆盖：同词异性、单词句、空句、罕见标签、长句、重复样本。
 */

function s(tokens: string[], tags: string[]): TaggedSentence {
  return { tokens, tags };
}

export const TAG_SET = [
  'N',
  'V',
  'A',
  'ADV',
  'P',
  'NUM',
  'M',
  'PRON',
  'CONJ',
  'PUNCT',
  'X',
] as const;

