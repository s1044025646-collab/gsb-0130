/** 重复样本（逐字重复），用于验证重复导入与跨集泄漏防护。 */
const duplicates: TaggedSentence[] = [
  s(['我', '爱', '中国'], ['PRON', 'V', 'N']),
  s(['三', '本', '书'], ['NUM', 'M', 'N']),
  s(['他', '吃', '苹果'], ['PRON', 'V', 'N']),
  s([], []),
];

/**
 * 仅出现在“额外验证集”的句子，含训练集从未见过的词：
 * 未知词策略测试使用（测试会单独作为验证句送入解码器）。
 */
export const validationOnly: TaggedSentence[] = [
  s(['企鹅', '吃', '磷虾'], ['N', 'V', 'N']),
  s(['她', '非常', '喜欢', '考拉'], ['PRON', 'ADV', 'V', 'N']),
  s(['九', '只', '考拉'], ['NUM', 'M', 'N']),
];

/** 构造完整夹具语料（含重复）。 */
export function buildCorpus(): TaggedSentence[] {
  return [...base, ...duplicates];
}

/** 去重后的唯一句数量。 */
export const UNIQUE_SENTENCE_COUNT = new Set(
  buildCorpus().map((x) => JSON.stringify([x.tokens, x.tags]))
).size;
